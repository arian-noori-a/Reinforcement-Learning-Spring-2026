"""Lightweight, autograder-ready artifacts for the deep-exploration homework.

Two entry points:

* :func:`build_fixtures` runs the student's eleven functions on small, fixed,
  CPU-only inputs (no training) and returns a flat dict of rounded arrays /
  scalars -- a deterministic signature of each implementation an autograder can
  diff against a reference. The two build-it-yourself constructors
  (``build_rnd_networks`` / ``build_bootstrap_ensemble``) leave the architecture to
  the student, so they are checked *structurally* (output shapes, which nets are
  frozen, ensemble size, head diversity) rather than by exact weights.
* :func:`export_artifacts` bundles those fixtures together with the (tiny) per-run
  ``.npz`` records and ``summary.json`` from the sweep into a single
  ``submission.zip`` (asserted < 10 MB).

Students do not edit this file; they only call ``export_artifacts`` from the
final notebook cell.
"""

from __future__ import annotations

import json
import shutil
import time
from pathlib import Path
from typing import Any

import numpy as np
import torch

import student_bootstrap
import student_metric
import student_rnd
from metrics import reachable_mask

# Small fixed batch size used across the RND / Bootstrap fixtures.
_B = 16
_N = 6  # DeepSea side length for the CPU fixtures


def _fixed_obs_batch(obs_size: int, batch: int = _B) -> np.ndarray:
    """A fixed, deterministic batch of one-hot-ish observations of width ``obs_size``."""
    obs = np.zeros((batch, obs_size), dtype=np.float32)
    obs[np.arange(batch), np.arange(batch) % obs_size] = 1.0
    return obs


def _round(x: Any, decimals: int = 6) -> np.ndarray:
    """Detach/convert to a rounded numpy array (works for tensors and scalars)."""
    if isinstance(x, torch.Tensor):
        x = x.detach().cpu().numpy()
    return np.round(np.asarray(x, dtype=np.float64), decimals)


def build_fixtures() -> dict[str, Any]:
    """Run the eleven student functions on fixed CPU inputs; return rounded results.

    Deterministic and training-free: every network is built *after* seeding, so a
    correct implementation always produces the same numbers. The action selectors
    are probed greedily (``epsilon=0``) so they too are deterministic. Raises
    ``NotImplementedError`` for any function the student has not filled in yet.
    """
    from bootstrap_dqn import BootstrappedDQN
    from bootstrap_dqn import Config as BootConfig
    from deepsea import DeepSea
    from rnd_dqn import Config as RNDConfig
    from rnd_dqn import RNDDoubleDQN

    out: dict[str, Any] = {}

    # -- Metric: hand-built (6,6) visitation grid over the reachable triangle ----
    reach = reachable_mask(_N)
    visit_counts = np.array(
        [
            [5, 0, 0, 0, 0, 0],
            [3, 4, 0, 0, 0, 0],
            [2, 1, 7, 0, 0, 0],
            [1, 0, 2, 6, 0, 0],
            [0, 0, 1, 3, 0, 0],
            [0, 0, 0, 2, 1, 0],
        ],
        dtype=np.int64,
    )
    coverage, entropy = student_metric.coverage_entropy(visit_counts, reach)
    out["metric_visit_counts"] = visit_counts
    out["metric_reachable"] = reach
    out["metric_coverage"] = _round(coverage)
    out["metric_entropy"] = _round(entropy)

    # -- RND: novelty bonus + TD target on a fixed batch -------------------------
    torch.manual_seed(0)
    rnd_env = DeepSea(size=_N, seed=0)
    rnd_cfg = RNDConfig(size=_N, seed=0, device="cpu", rnd_output_dim=64)
    rnd_agent = RNDDoubleDQN(rnd_env, rnd_cfg)
    next_obs = torch.as_tensor(_fixed_obs_batch(rnd_env.observation_size))

    intrinsic, predictor_loss = student_rnd.rnd_intrinsic_bonus(rnd_agent, next_obs)
    out["rnd_intrinsic_mean"] = _round(intrinsic.mean())
    out["rnd_intrinsic_std"] = _round(intrinsic.std())
    out["rnd_intrinsic_head"] = _round(intrinsic[:8])
    out["rnd_predictor_loss"] = _round(predictor_loss)

    shaped_reward = torch.linspace(0.0, 1.0, _B)
    done = torch.tensor([0.0, 1.0] * (_B // 2))
    rnd_target = student_rnd.rnd_td_target(rnd_agent, shaped_reward, next_obs, done)
    out["rnd_td_target"] = _round(rnd_target)

    # The full critic loss assembled on the shaped reward (RND action selection is
    # provided, not a student task, so it is not fingerprinted).
    rnd_action = torch.arange(_B) % rnd_env.num_actions
    rnd_loss = student_rnd.rnd_q_loss(
        rnd_agent, next_obs, rnd_action, shaped_reward, next_obs, done
    )
    out["rnd_q_loss"] = _round(rnd_loss)

    # Student-built RND networks (architecture is their choice, so check structure,
    # not weights): both emit output_dim features; the target is frozen, the
    # predictor trains.
    with torch.no_grad():
        out["rnd_target_out_shape"] = np.asarray(
            tuple(rnd_agent.rnd_target(next_obs).shape), dtype=np.int64
        )
        out["rnd_pred_out_shape"] = np.asarray(
            tuple(rnd_agent.rnd_predictor(next_obs).shape), dtype=np.int64
        )
    out["rnd_target_frozen"] = np.asarray(
        not any(p.requires_grad for p in rnd_agent.rnd_target.parameters())
    )
    out["rnd_pred_trainable"] = np.asarray(
        any(p.requires_grad for p in rnd_agent.rnd_predictor.parameters())
    )

    # -- Bootstrap: per-head target + posterior-sampling histogram ---------------
    torch.manual_seed(0)
    boot_env = DeepSea(size=_N, seed=0)
    boot_cfg = BootConfig(
        size=_N, seed=0, device="cpu", num_heads=5, prior_scale=3.0, mask_prob=0.5
    )
    boot_agent = BootstrappedDQN(boot_env, boot_cfg)
    boot_obs = torch.as_tensor(_fixed_obs_batch(boot_env.observation_size))
    reward = torch.linspace(0.0, 1.0, _B)
    boot_done = torch.tensor([0.0, 1.0] * (_B // 2))
    head_target = student_bootstrap.boot_head_target(
        boot_agent,
        boot_agent.ensemble[0],
        boot_agent.target_ensemble[0],
        reward,
        boot_obs,
        boot_done,
    )
    out["boot_head0_target"] = _round(head_target)

    # Behaviour policy (greedy under head 0) and evaluation policy (greedy under
    # the ensemble mean) on a few fixed single observations.
    boot_rows = _fixed_obs_batch(boot_env.observation_size, 8)
    out["boot_actions_head0"] = np.array(
        [student_bootstrap.boot_select_action(boot_agent, boot_rows[i], 0) for i in range(8)],
        dtype=np.int64,
    )
    out["boot_actions_eval"] = np.array(
        [student_bootstrap.boot_eval_action(boot_agent, boot_rows[i]) for i in range(8)],
        dtype=np.int64,
    )

    # Masked per-head loss on a fixed bootstrap mask (some bits unset).
    boot_action = torch.arange(_B) % boot_env.num_actions
    boot_mask = torch.tensor([1.0, 1.0, 0.0, 1.0] * (_B // 4))
    head_loss = student_bootstrap.boot_head_loss(
        boot_agent,
        boot_agent.ensemble[0],
        boot_agent.target_ensemble[0],
        boot_obs,
        boot_action,
        reward,
        boot_obs,
        boot_done,
        boot_mask,
    )
    out["boot_head0_loss"] = _round(head_loss)

    rng = np.random.default_rng(0)
    draws = np.array(
        [student_bootstrap.boot_sample_head(boot_agent, rng) for _ in range(1000)],
        dtype=np.int64,
    )
    out["boot_head_hist"] = np.bincount(draws, minlength=boot_cfg.num_heads)

    # Student-built ensemble: structural signature. Right number of heads, every
    # head's prior is frozen, and the heads start out diverse (their frozen priors
    # disagree) -- diversity is the whole point of the ensemble.
    out["boot_ensemble_size"] = np.asarray(len(boot_agent.ensemble), dtype=np.int64)
    out["boot_prior_frozen"] = np.asarray(
        not any(
            p.requires_grad
            for head in boot_agent.ensemble
            for p in head.prior.parameters()
        )
    )
    with torch.no_grad():
        prior_outs = torch.stack(
            [head.prior(boot_obs) for head in boot_agent.ensemble], dim=0
        )
    out["boot_heads_distinct"] = np.asarray(bool(prior_outs.std(dim=0).mean() > 1e-6))

    return out


def _total_runtime(results_dir: Path) -> float:
    """Sum the recorded sweep wall-time across the two variants (0 if missing)."""
    total = 0.0
    for variant in ("normal", "noisy"):
        manifest = results_dir / variant / "manifest.json"
        if manifest.exists():
            total += float(json.loads(manifest.read_text()).get("elapsed_seconds", 0.0))
    return total


def export_artifacts(
    results_dir: str = "results",
    out: str = "submission.zip",
    student_number: str = "",
) -> str:
    """Bundle fixtures + run records + summaries into ``out`` (< 10 MB). Returns ``out``.

    ``student_number`` is written into the package (``meta.json``) so the submission
    carries the student's identity. Re-runnable: rebuilds a fresh ``submission/``
    staging dir each call.
    """
    student_number = str(student_number).strip()
    assert student_number, (
        "export_artifacts: student_number is empty -- set STUDENT_NUMBER at the top "
        "of the notebook and re-run this cell."
    )

    results = Path(results_dir)
    staging = Path("submission")
    if staging.exists():
        shutil.rmtree(staging)
    staging.mkdir(parents=True)

    # 1. Deterministic fixtures from the student's eleven functions.
    fixtures = build_fixtures()
    np.savez_compressed(staging / "fixtures.npz", **fixtures)

    # 2. Per-run records + per-variant summary for the sweep.
    for variant in ("normal", "noisy"):
        src_runs = results / variant / "runs"
        for npz in sorted(src_runs.rglob("*.npz")):
            dst = staging / variant / npz.relative_to(results / variant)
            dst.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(npz, dst)
        summary = results / variant / "summary.json"
        if summary.exists():
            shutil.copy2(summary, staging / variant / "summary.json")

    # 3. Provenance (includes the student number for manual cross-check vs. the
    # STUDENT_NUMBER set in the submitted notebook).
    meta = {
        "student_number": student_number,
        "timestamp": time.strftime("%Y-%m-%dT%H:%M:%S"),
        "torch_version": torch.__version__,
        "numpy_version": np.__version__,
        "device": "cuda" if torch.cuda.is_available() else "cpu",
        "total_runtime_seconds": _total_runtime(results),
    }
    (staging / "meta.json").write_text(json.dumps(meta, indent=2))

    # 4. Zip and check the size budget.
    zip_base = out[:-4] if out.endswith(".zip") else out
    archive = shutil.make_archive(zip_base, "zip", root_dir=staging)
    size_mb = Path(archive).stat().st_size / 1e6
    print(f"wrote {archive}  ({size_mb:.2f} MB)  student_number={student_number}")
    assert size_mb < 10.0, f"submission too large: {size_mb:.2f} MB (budget 10 MB)"
    return archive
