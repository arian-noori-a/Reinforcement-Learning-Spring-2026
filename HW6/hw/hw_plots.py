def _show_png(path: str | Path, *, width: float = 8.0) -> None:
    """Display a pre-rendered PNG inline, scaled to ``width`` inches."""
    path = Path(path)
    if not path.exists():
        print(f"(missing figure: {path} -- run the experiment + analysis first)")
        return
    img = plt.imread(path)
    h, w = img.shape[:2]
    fig, ax = plt.subplots(figsize=(width, width * h / w))
    ax.imshow(img)
    ax.axis("off")
    plt.show()
    plt.close(fig)


