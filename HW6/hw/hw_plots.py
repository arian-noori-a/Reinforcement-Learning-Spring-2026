# ----------------------------------------------------------------------------
def _draw_board(ax, size: int, *, noisy: bool, noise_columns: tuple[int, ...]) -> None:
    """Draw one DeepSea board: reachable lower triangle, start, treasure, TV."""
    for r in range(size):
        for c in range(size):
            reachable = c <= r
            if noisy and c in noise_columns:
                face = "#fde68a"  # noisy-TV column
            elif reachable:
                face = "#dbeafe"  # reachable water
            else:
                face = "#f3f4f6"  # unreachable (upper triangle)
            ax.add_patch(
                Rectangle(
                    (c - 0.5, r - 0.5), 1, 1,
                    facecolor=face, edgecolor="#cbd5e1", lw=0.5,
                )
            )
    ax.text(0, 0, "S", ha="center", va="center", fontsize=10, fontweight="bold")
    ax.add_patch(
        Rectangle(
            (size - 1 - 0.5, size - 1 - 0.5), 1, 1,
            fill=False, edgecolor="red", lw=2,
        )
    )
    ax.text(
        size - 1, size - 1, "$", ha="center", va="center",
        fontsize=11, color="red", fontweight="bold",
    )
    ax.set_xlim(-0.5, size - 0.5)
    ax.set_ylim(size - 0.5, -0.5)  # row 0 at the top
    ax.set_aspect("equal")
    ax.set_xlabel("column (treasure on the right)")
    ax.set_ylabel("row (forced descent)")
    ax.set_xticks(range(size))
    ax.set_yticks(range(size))
    ax.tick_params(labelsize=7)


def show_demo_boards(size: int, noise_columns: tuple[int, ...] = (0,)) -> None:
    """Render the normal and noisy DeepSea boards side by side."""
    fig, axes = plt.subplots(1, 2, figsize=(11, 5.2))
    _draw_board(axes[0], size, noisy=False, noise_columns=noise_columns)
    axes[0].set_title(f"Normal DeepSea (N={size})", fontsize=11)
    _draw_board(axes[1], size, noisy=True, noise_columns=noise_columns)
    cols = ", ".join(str(c) for c in noise_columns)
    axes[1].set_title(f"Noisy-TV DeepSea (N={size}, noise in column {cols})", fontsize=11)
    fig.suptitle(
        "Start top-left (S); descend one row per step; treasure (boxed $) "
        "bottom-right.\nYellow column = reward-irrelevant random features active "
        "only while sitting there.",
        fontsize=9,
    )
    fig.tight_layout()
    plt.show()
    plt.close(fig)


