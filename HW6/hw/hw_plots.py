# The mechanism figure: normal vs noisy exploration-bonus overlay
# ----------------------------------------------------------------------------
def _intrinsic_matrix(runs: list[dict], grid: np.ndarray) -> np.ndarray:
    """Stack each seed's exploration-bonus series interpolated onto ``grid``."""
    return np.vstack(
        [
            analysis._series_on_grid(r["intr_steps"], r["intr_values"], grid, 200)
            for r in runs
        ]
    )


def _overlay(ax, results_dir: str, agent: str) -> None:
    """Overlay one agent's bonus series for the normal vs noisy variant."""
    base = Path(results_dir)
    styles = {"normal": ("-", "normal"), "noisy": (":", "noisy-TV")}
    for variant, (ls, tag) in styles.items():
        data = analysis.load_experiment(base / variant)
        runs = data["runs"]
        size = int(data["manifest"]["sizes"][0])
        if (agent, size) not in runs:
            continue
        run_list = runs[agent, size]
        grid = analysis._grid(run_list)
        mat = _intrinsic_matrix(run_list, grid)
        mean, lo, hi = analysis._bootstrap_mean_ci(mat)
        color = AGENT_COLORS[agent]
        ax.plot(grid, mean, color=color, lw=2, ls=ls, label=tag)
        ax.fill_between(grid, lo, hi, color=color, alpha=0.15)
    ax.set_xlabel("env steps")
    ax.legend(fontsize=9)


def show_mechanism(results_dir: str = "results") -> None:
    """Overlay RND novelty bonus and Bootstrap disagreement, normal vs noisy.

    This is the crux figure: the RND novelty bonus should *decay* on normal
    DeepSea but stay pinned high on the noisy variant (the predictor can never fit
    the random TV), while the Bootstrap ensemble's value-head disagreement decays
    on both because reward-irrelevant input noise produces no lasting epistemic
    disagreement.
    """
    fig, axes = plt.subplots(1, 2, figsize=(12, 4.6))
    _overlay(axes[0], results_dir, "rnd_dqn")
    axes[0].set_ylabel("normalised RND novelty bonus")
    axes[0].set_title("RND novelty bonus: normal vs noisy")
    _overlay(axes[1], results_dir, "bootstrap_dqn")
    axes[1].set_ylabel("ensemble Q disagreement (std)")
    axes[1].set_title("Bootstrap disagreement: normal vs noisy")
    fig.suptitle("Mechanism: aleatoric noise traps prediction-error novelty, "
                 "not value-head disagreement", fontsize=10)
    fig.tight_layout()
    plt.show()
    plt.close(fig)
